def match_dispatch(job_seeker_id: str, incoming: IncomingMessage) -> dict | None:
    """Message-ID chain first, recipient plus subject only as a fallback."""
    match = repo.dispatch_by_message_ids(job_seeker_id, incoming.thread_ids)
    if match:
        return match
    # A bounce comes from the mailer daemon, so the address to look up is the
    # one that failed, not the sender of the report.
    address = (
        (incoming.bounce.recipient if incoming.bounce else "") or incoming.from_address
    )
    if not address:
        return None
    return repo.dispatch_by_recipient(job_seeker_id, address, subject=incoming.subject)


def record_incoming(
    job_seeker_id: str, incoming: IncomingMessage, *, source: str = "poll"
) -> dict:
    """Apply one inbound message to the send log.  Idempotent on Message-ID."""
    if incoming.message_id and repo.reply_exists(job_seeker_id, incoming.message_id):
        return {"status": "duplicate", "message_id": incoming.message_id}

    match = match_dispatch(job_seeker_id, incoming)
    dispatch_id = match["id"] if match else None
    chain = incoming.thread_ids

    if incoming.is_bounce:
        outcome = _apply_bounce(job_seeker_id, incoming, match, source=source)
    else:
        outcome = _apply_reply(job_seeker_id, incoming, match, source=source)

    reply_id = repo.record_reply(
        job_seeker_id,
        {
            "dispatch_id": dispatch_id,
            "from_address": incoming.from_address,
            "subject": incoming.subject,
            "body": incoming.body,
            "received_at": incoming.received_at,
            "message_id": incoming.message_id,
            "in_reply_to": incoming.in_reply_to or (chain[0] if chain else None),
            "classification": outcome["classification"],
        },
    )
    outcome["incoming_reply_id"] = reply_id
    outcome["dispatch_id"] = dispatch_id
    return outcome


def _apply_bounce(
    job_seeker_id: str, incoming: IncomingMessage, match: dict | None, *, source: str
) -> dict:
    report = incoming.bounce or BounceReport()
    permanent = report.permanent
    detail = {
        "source": source,
        "action": report.action,
        "status": report.status,
        "diagnostic": report.diagnostic,
        "reporting_mta": report.reporting_mta,
        "failed_recipient": report.recipient,
        "permanent": permanent,
    }
    if match:
        repo.update_dispatch(
            match["id"],
            {
                # A 4.x.y deferral is not a failure yet: the sending MTA is still
                # retrying, so the dispatch keeps its status and records the detail.
                **({"delivery_status": "bounced"} if permanent else {}),
                "bounce_detected_at": incoming.received_at or utcnow(),
                "delivery_detail": detail,
            },
        )
        repo.notify(
            job_seeker_id,
            "reply",
            f"Delivery failed: {match.get('recipient_email')}",
            report.diagnostic or report.status,
            {"dispatch_id": match["id"], "permanent": permanent},
            dedup_key=f"bounce:{match['id']}",
        )
        record_audit(
            "dispatch.bounced",
            "dispatch",
            match["id"],
            seeker_id=job_seeker_id,
            actor="system",
            detail=detail,
        )
    else:
        log.info("Bounce for %s did not match a dispatch", report.recipient or incoming.subject)
    return {
        "status": "bounced" if permanent else "deferred",
        "classification": "bounce",
        "detail": detail,
    }


def _apply_reply(
    job_seeker_id: str, incoming: IncomingMessage, match: dict | None, *, source: str
) -> dict:
    classification = "auto_reply" if incoming.is_auto_reply else None
    objected = False

    if match and not incoming.is_auto_reply:
        repo.update_dispatch(
            match["id"],
            {
                "reply_detected_at": incoming.received_at or utcnow(),
                "delivery_status": "delivered",
            },
        )
        repo.notify(
            job_seeker_id,
            "reply",
            f"Reply from {incoming.from_name or incoming.from_address}",
            incoming.subject,
            {"dispatch_id": match["id"], "from": incoming.from_address},
        )
        record_audit(
            "dispatch.replied",
            "dispatch",
            match["id"],
            seeker_id=job_seeker_id,
            actor="system",
            detail={"from": incoming.from_address, "source": source},
        )

    # NFR-302: an objection blocks the address permanently and for every job
    # seeker, so it is honoured the moment it is read - not when someone gets
    # round to reviewing the reply.
    if incoming.from_address and not incoming.is_auto_reply and is_objection(incoming.body):
        contacts_repo.record_objection(
            incoming.from_address,
            reason="Objection received by e-mail reply",
            source="reply",
        )
        classification = "objection"
        objected = True
        record_audit(
            "contact.objected",
            "contact",
            incoming.from_address,
            seeker_id=job_seeker_id,
            actor="system",
            detail={"source": "reply", "dispatch_id": match["id"] if match else None},
        )

    return {
        "status": "objection"
        if objected
        else ("auto_reply" if incoming.is_auto_reply else "reply"),
        "classification": classification,
        "matched": bool(match),
    }


def apply_provider_event(event: dict, *, delivery_id: str, provider: str) -> dict:
    """Apply one webhook event (Resend) to the send log (FR-326).

    Idempotent: the provider retries until it is acknowledged, so the delivery
    id is recorded first and a replay returns without touching the dispatch.
    """
    event_id = delivery_id or str(event.get("provider_message_id") or utcnow())
    if repo.webhook_event_seen(event_id):
        return {"status": "duplicate", "event_id": event_id}

    # The webhook carries no session, so the dispatch has to identify its own
    # job seeker.  The provider's own send id - stored as ``thread_id`` when the
    # message went out - is ours and is unique, so it is the only key used here;
    # matching on a header would mean searching across job seekers (FR-344).
    match = None
    if event.get("provider_message_id"):
        match = repo.dispatch_by_provider_message_id(str(event["provider_message_id"]))

    repo.record_webhook_event(
        event_id,
        provider=provider,
        event_type=str(event.get("event_type") or "unknown"),
        provider_message_id=event.get("provider_message_id"),
        recipient=event.get("recipient"),
        dispatch_id=match["id"] if match else None,
        payload=event.get("raw"),
    )

    if match is None:
        log.info("%s event %s matched no dispatch", provider, event.get("event_type"))
        return {"status": "unmatched", "event_type": event.get("event_type")}

    seeker_id = match["job_seeker_id"]
    status = event.get("status")
    values: dict[str, Any] = {"delivery_detail": {k: v for k, v in event.items() if k != "raw"}}
    if status:
        values["delivery_status"] = status
    if status == "bounced":
        values["bounce_detected_at"] = utcnow()
    repo.update_dispatch(match["id"], values)

    if status == "bounced":
        repo.notify(
            seeker_id,
            "reply",
            f"Delivery failed: {match.get('recipient_email')}",
            event.get("reason"),
            {"dispatch_id": match["id"], "event_type": event.get("event_type")},
            dedup_key=f"bounce:{match['id']}",
        )
        # A spam complaint is an objection in everything but name (NFR-302).
        if event.get("event_type") == "email.complained" and match.get("recipient_email"):
            contacts_repo.record_objection(
                match["recipient_email"], reason="Spam complaint via Resend", source="unsubscribe"
            )
    record_audit(
        f"dispatch.{status or 'event'}",
        "dispatch",
        match["id"],
        seeker_id=seeker_id,
        actor="system",
        detail={"provider": provider, "event_type": event.get("event_type")},
    )
    repo.mark_webhook_processed(event_id, match["id"])
    return {"status": status or "recorded", "dispatch_id": match["id"]}


