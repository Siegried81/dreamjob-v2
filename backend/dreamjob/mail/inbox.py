def poll_account(account: dict, *, max_messages: int = 100) -> dict:
    """Read what has arrived in one mailbox since the last cursor.

    Chooses the transport the mailbox can actually use: IMAP when the granted
    scopes include full mailbox access, otherwise the Gmail API, which is what
    the ``gmail.readonly`` scope Dream Job requests supports.
    """
    from dreamjob.mail.gmail import IMAP_SCOPE, GmailBackend  # noqa: PLC0415

    if account.get("backend") != "gmail_oauth":
        return {
            "account_id": account.get("id"),
            "polled": 0,
            "skipped": f"{account.get('backend')} has no mailbox to poll; it reports by webhook",
        }

    backend = GmailBackend(account)
    scopes = set(str(account.get("scopes") or "").split())
    try:
        if IMAP_SCOPE in scopes:
            result = poll_imap(account, backend, max_messages=max_messages)
        else:
            result = poll_gmail_api(account, backend, max_messages=max_messages)
    except Exception as exc:  # noqa: BLE001 - a failing mailbox must not stop the job
        log.exception("Polling mailbox %s failed", account.get("address"))
        repo.save_poll_state(account["id"], {"last_error": str(exc)[:500]})
        return {"account_id": account["id"], "polled": 0, "error": str(exc)[:500]}
    return result


def poll_gmail_api(account: dict, backend: Any, *, max_messages: int = 100) -> dict:
    """Poll with ``gmail.readonly``: search since the cursor, fetch raw, apply."""
    state = repo.get_poll_state(account["id"]) or {}
    since = state.get("last_polled_at")
    query = "-in:sent -in:chats"
    if since:
        # Gmail's `after:` is whole-second epoch and is inclusive; a minute of
        # overlap costs nothing because record_incoming is idempotent.
        epoch = int(datetime.fromisoformat(since).timestamp()) - 60
        query = f"{query} after:{epoch}"
    else:
        query = f"{query} newer_than:7d"

    ids = backend.list_message_ids(query, max_results=max_messages)
    outcomes = {"reply": 0, "bounced": 0, "deferred": 0, "auto_reply": 0, "objection": 0}
    seen = 0
    for gmail_id in ids:
        raw = backend.fetch_raw(gmail_id)
        incoming = parse_message(raw)
        if incoming.from_address == str(account.get("address", "")).lower():
            continue
        result = record_incoming(account["job_seeker_id"], incoming, source="gmail_api")
        seen += 1
        if result["status"] in outcomes:
            outcomes[result["status"]] += 1

    repo.save_poll_state(
        account["id"],
        {
            "last_polled_at": utcnow(),
            "last_error": None,
            "messages_seen": int(state.get("messages_seen") or 0) + seen,
        },
    )
    return {"account_id": account["id"], "polled": seen, "transport": "gmail_api", **outcomes}


def _xoauth2_string(address: str, access_token: str) -> str:
    return f"user={address}\x01auth=Bearer {access_token}\x01\x01"


def poll_imap(
    account: dict,
    backend: Any,
    *,
    max_messages: int = 100,
    password: str | None = None,
) -> dict:
    """Poll over IMAP with :mod:`imaplib`, resuming from the stored UID.

    UIDVALIDITY is checked first: when the server changes it the stored UIDs no
    longer mean anything and the cursor has to be dropped rather than trusted,
    which is the difference between resuming and silently reading nothing ever
    again.
    """
    settings = get_settings()
    state = repo.get_poll_state(account["id"]) or {}
    address = str(account.get("address") or "")

    client = imaplib.IMAP4_SSL(settings.imap_host, settings.imap_port)
    try:
        if password:
            client.login(address, password)
        else:
            token = backend.access_token()
            client.authenticate(
                "XOAUTH2", lambda _challenge: _xoauth2_string(address, token).encode()
            )
        folder = state.get("folder") or "INBOX"
        client.select(folder, readonly=True)

        typ, data = client.status(folder, "(UIDVALIDITY)")
        validity = ""
        if typ == "OK" and data:
            match = re.search(rb"UIDVALIDITY (\d+)", data[0] or b"")
            validity = match.group(1).decode() if match else ""

        last_uid = int(state.get("last_uid") or 0)
        if validity and state.get("uid_validity") and validity != state["uid_validity"]:
            log.info("UIDVALIDITY changed on %s; restarting the cursor", address)
            last_uid = 0

        typ, data = client.uid("SEARCH", None, f"UID {last_uid + 1}:*")
        uids = [int(u) for u in (data[0] or b"").split() if int(u) > last_uid][:max_messages]

        outcomes = {"reply": 0, "bounced": 0, "deferred": 0, "auto_reply": 0, "objection": 0}
        seen = 0
        highest = last_uid
        for uid in uids:
            typ, payload = client.uid("FETCH", str(uid), "(RFC822)")
            if typ != "OK" or not payload or not isinstance(payload[0], tuple):
                continue
            incoming = parse_message(payload[0][1])
            highest = max(highest, uid)
            if incoming.from_address == address.lower():
                continue
            result = record_incoming(account["job_seeker_id"], incoming, source="imap")
            seen += 1
            if result["status"] in outcomes:
                outcomes[result["status"]] += 1

        repo.save_poll_state(
            account["id"],
            {
                "folder": folder,
                "uid_validity": validity or state.get("uid_validity"),
                "last_uid": highest,
                "last_polled_at": utcnow(),
                "last_error": None,
                "messages_seen": int(state.get("messages_seen") or 0) + seen,
            },
        )
        return {"account_id": account["id"], "polled": seen, "transport": "imap", **outcomes}
    finally:
        try:
            client.logout()
        except (OSError, imaplib.IMAP4.error):  # pragma: no cover - best effort
            pass


def poll_all(job_seeker_id: str | None = None, *, max_messages: int = 100) -> list[dict]:
    """Poll every connected mailbox; one failure does not stop the others."""
    accounts = repo.accounts_to_poll("gmail_oauth")
    if job_seeker_id:
        accounts = [a for a in accounts if a["job_seeker_id"] == job_seeker_id]
    return [poll_account(a, max_messages=max_messages) for a in accounts]
