def _header_ids(value: str | None) -> list[str]:
    return MESSAGE_ID_RE.findall(value or "")


def _first_address(value: str | None) -> tuple[str, str]:
    for name, addr in getaddresses([value or ""]):
        if addr:
            return addr.strip().lower(), name.strip()
    return "", ""


def _received_at(message: EmailMessage) -> str:
    raw = message.get("Date")
    if raw:
        try:
            return parsedate_to_datetime(raw).astimezone(UTC).isoformat(timespec="seconds")
        except (TypeError, ValueError):
            pass
    return utcnow()


def _plain_body(message: EmailMessage, limit: int = 20_000) -> str:
    """The readable text, preferring text/plain and falling back to stripped HTML."""
    try:
        part = message.get_body(preferencelist=("plain", "html"))
    except Exception:  # noqa: BLE001 - malformed MIME must not stop the poll
        part = None
    if part is None:
        return ""
    try:
        content = part.get_content()
    except Exception:  # noqa: BLE001 - unknown charset
        payload = part.get_payload(decode=True) or b""
        content = payload.decode("utf-8", errors="replace")
    if part.get_content_subtype() == "html":
        content = re.sub(r"<[^>]+>", " ", content)
    return re.sub(r"[ \t]+", " ", str(content)).strip()[:limit]


def parse_delivery_status(message: EmailMessage) -> BounceReport | None:
    """Read the RFC 3464 report parts, not the prose (FR-326).

    ``message/delivery-status`` is a sequence of RFC 822-style field blocks: one
    per-message block, then one per-recipient block carrying ``Action`` and
    ``Status``.  ``message/rfc822`` (or ``text/rfc822-headers``) holds what was
    sent, which is where the original ``Message-ID`` comes from.
    """
    content_type = message.get_content_type()
    report_type = str(message.get_param("report-type", "") or "").lower()
    if content_type != "multipart/report" and report_type != "delivery-status":
        return None

    report = BounceReport()
    for part in message.walk():
        subtype = part.get_content_type()
        if subtype == "message/delivery-status":
            for block in part.get_payload():
                if not hasattr(block, "get"):
                    continue
                action = str(block.get("Action", "") or "")
                if action:
                    report.action = action.strip().lower()
                status = str(block.get("Status", "") or "").strip()
                if status:
                    report.status = status
                recipient = block.get("Final-Recipient") or block.get("Original-Recipient")
                if recipient:
                    report.recipient = str(recipient).split(";")[-1].strip().lower()
                diagnostic = block.get("Diagnostic-Code")
                if diagnostic:
                    report.diagnostic = str(diagnostic).strip()[:500]
                mta = block.get("Reporting-MTA")
                if mta:
                    report.reporting_mta = str(mta).split(";")[-1].strip()
        elif subtype in ("message/rfc822", "text/rfc822-headers"):
            original = part.get_payload(0) if part.is_multipart() else None
            if original is None:
                try:
                    original = email.message_from_string(
                        str(part.get_payload()), policy=email.policy.default
                    )
                except Exception:  # noqa: BLE001
                    original = None
            if original is not None:
                ids = _header_ids(original.get("Message-ID"))
                if ids:
                    report.original_message_id = ids[0]
                if not report.recipient:
                    report.recipient, _ = _first_address(original.get("To"))
    return report if (report.action or report.status or report.original_message_id) else None


def parse_message(raw: bytes) -> IncomingMessage:
    """Parse one RFC 822 message into the fields FR-326 matches and records on."""
    message: EmailMessage = email.message_from_bytes(raw, policy=email.policy.default)
    from_address, from_name = _first_address(message.get("From"))
    to_addresses = [a for _, a in getaddresses([message.get("To", "")]) if a]

    bounce = parse_delivery_status(message)
    incoming = IncomingMessage(
        message_id=(_header_ids(message.get("Message-ID")) or [""])[0],
        in_reply_to=(_header_ids(message.get("In-Reply-To")) or [""])[0],
        references=_header_ids(message.get("References")),
        from_address=from_address,
        from_name=from_name,
        to_addresses=[a.lower() for a in to_addresses],
        subject=str(message.get("Subject", "") or ""),
        received_at=_received_at(message),
        body=_plain_body(message),
        bounce=bounce,
        is_bounce=bool(bounce and bounce.failed),
        raw_size=len(raw),
    )
    incoming.is_auto_reply = _looks_automatic(message, incoming)
    return incoming


def _looks_automatic(message: EmailMessage, incoming: IncomingMessage) -> bool:
    """Out-of-office and vacation replies, which must not clear a follow-up."""
    if incoming.is_bounce:
        return True
    for header in AUTO_REPLY_HEADERS:
        value = str(message.get(header, "") or "").lower()
        if value and value != "no":
            return True
    if str(message.get("Precedence", "") or "").lower() in ("bulk", "auto_reply", "junk"):
        return True
    return False


def _sentence_pattern(template: str) -> re.Pattern[str]:
    """Match one of our own objection sentences, whatever address it names."""
    joined = r"\S+".join(re.escape(part) for part in template.split("{address}"))
    # re.escape() escapes spaces too, and the sentence is line-wrapped when it
    # is sent, so every run of (escaped) whitespace becomes a whitespace class.
    return re.compile(re.sub(r"(?:\\?\s)+", r"\\s+", joined), re.IGNORECASE)


#: The sentence NFR-302 puts at the foot of every message we send.  A reply
#: quotes it back at us, so it has to be removed before the reply is read for
#: an objection - otherwise every quoted reply looks like one.
OWN_OBJECTION_SENTENCES: tuple[re.Pattern[str], ...] = tuple(
    _sentence_pattern(template) for template in composer.OBJECTION_SENTENCE.values()
)

#: Where a reply stops being the sender's own words and becomes the message
#: they are answering: the quote markers the common clients write.
QUOTED_LINE = re.compile(
    r"^\s*(?:>"
    r"|-{2,}\s*original message"
    r"|_{5,}"
    r"|on\b.{0,160}\bwrote:"
    r"|(?:op|le|am)\b.{0,160}\b(?:schreef|geschreven|écrit|schrieb):"
    r"|(?:from|van|de|von|sent|verzonden|gesendet|envoyé|to|aan|à)\s*:"
    r")",
    re.IGNORECASE,
)


def own_words(text: str) -> str:
    """What the sender actually typed, with the message they quoted removed.

    Quoted lines are dropped rather than everything below the first one, so a
    reply written underneath the quotation - the normal style in half of
    Europe - is still read (NFR-302, FR-326).
    """
    kept = [line for line in (text or "").splitlines() if not QUOTED_LINE.match(line)]
    body = "\n".join(kept)
    # A client that quotes without markers, or that sent HTML whose tags have
    # been stripped, leaves the sentence itself in place; remove that too.
    for pattern in OWN_OBJECTION_SENTENCES:
        body = pattern.sub(" ", body)
    return body.strip()


def is_objection(text: str) -> bool:
    """NFR-302: did the recipient ask not to be contacted again?

    Read on the sender's own words only.  Blocking a contact is permanent and
    applies to every job seeker, so a phrase that is only present because the
    reply quotes what we sent must not trigger it.
    """
    lowered = own_words(text).lower()
    return any(phrase in lowered for phrase in OBJECTION_PHRASES)


