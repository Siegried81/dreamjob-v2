"""Reply and bounce detection (FR-326, NFR-302).

FR-326 asks that bounces and replies be detected and reflected in the
opportunity status.  Two mechanisms feed one set of rules:

* **Polling**, for a connected Gmail mailbox.  ``poll_account`` reads what has
  arrived since the last cursor - through the Gmail API with the
  ``gmail.readonly`` scope Dream Job actually requests, or over IMAP with
  :mod:`imaplib` when the mailbox already grants ``https://mail.google.com/``
  (see :mod:`dreamjob.mail.gmail` for why that scope is not requested).
* **Webhooks**, for Resend, which has no mailbox to poll.

Bounces are recognised structurally, not by reading subject lines.  A delivery
failure is a delivery status notification (RFC 3464): a ``multipart/report``
whose ``report-type`` is ``delivery-status``, carrying a
``message/delivery-status`` part with ``Action:`` and ``Status:`` fields and,
usually, a ``message/rfc822`` copy of what was sent.  Parsing that gives three
things that subject matching cannot: whether the failure is permanent
(``5.x.y``) or transient (``4.x.y``), which recipient failed when a message had
several, and the original ``Message-ID`` - which is the most reliable key back
to the dispatch, because the bounce itself is a new message from a mailer
daemon and shares no headers with the reply chain.

Matching order, for both replies and bounces: ``In-Reply-To``, then every id in
``References``, then the ``Message-ID`` quoted inside a report, and only then
recipient plus subject.  The fallback is last because two applications to the
same company can share a subject.
"""

