log = logging.getLogger(__name__)

MESSAGE_ID_RE = re.compile(r"<[^<>@\s]+@[^<>\s]+>")

#: RFC 3464 ``Action`` values that mean the message did not arrive.
FAILED_ACTIONS = {"failed", "delayed"}

#: NFR-302 - phrasings that count as an objection, in the four languages the
#: introduction e-mail is written in.  The message we send asks for exactly the
#: first entry of each language, so the common case is an exact hit; the rest
#: catch the ways people actually phrase it.
OBJECTION_PHRASES: tuple[str, ...] = (
    "no thank you", "unsubscribe", "remove me", "do not contact", "don't contact",
    "stop contacting", "opt out", "take me off",
    "liever niet", "uitschrijven", "geen interesse in dit soort", "niet meer contact",
    "graag verwijderen",
    "non merci", "désinscri", "desinscri", "ne me contactez plus", "me retirer",
    "nein danke", "abmelden", "keine weiteren", "nicht mehr kontaktieren",
)

#: Headers that mark a message as generated by a machine rather than a person.
AUTO_REPLY_HEADERS = ("auto-submitted", "x-autoreply", "x-autorespond", "x-auto-response-suppress")


@dataclass
class BounceReport:
    """The machine-readable half of a delivery status notification (RFC 3464)."""

    action: str = ""
    status: str = ""
    recipient: str = ""
    diagnostic: str = ""
    reporting_mta: str = ""
    original_message_id: str = ""

    @property
    def permanent(self) -> bool:
        """A 5.x.y status is permanent; 4.x.y is a transient deferral."""
        return self.status.startswith("5")

    @property
    def failed(self) -> bool:
        return self.action.lower() in FAILED_ACTIONS or self.status.startswith(("4", "5"))


@dataclass
class IncomingMessage:
    """One parsed inbound message, whatever transport it arrived over."""

    message_id: str = ""
    in_reply_to: str = ""
    references: list[str] = field(default_factory=list)
    from_address: str = ""
    from_name: str = ""
    to_addresses: list[str] = field(default_factory=list)
    subject: str = ""
    received_at: str = ""
    body: str = ""
    is_bounce: bool = False
    is_auto_reply: bool = False
    bounce: BounceReport | None = None
    raw_size: int = 0

    @property
    def thread_ids(self) -> list[str]:
        """Every id that could name the message this one answers, best first."""
        ids: list[str] = []
        candidates = [self.in_reply_to]
        if self.bounce:
            candidates.append(self.bounce.original_message_id)
        candidates.extend(reversed(self.references))
        for candidate in candidates:
            if candidate and candidate not in ids:
                ids.append(candidate)
        return ids


